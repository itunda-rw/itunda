#!/usr/bin/env node

import { mkdir, writeFile } from 'node:fs/promises';

const base = process.env.ITUNDA_API_BASE_URL?.replace(/\/$/, '');
if (!base) {
  console.error('ITUNDA_API_BASE_URL is required, for example https://api.itunda.im');
  process.exit(2);
}

const url = base + '/openapi.json';
const response = await fetch(url, {
  headers: { Accept: 'application/json' },
});

if (!response.ok) {
  console.error(`OpenAPI endpoint returned HTTP ${response.status}`);
  process.exit(1);
}

const document = await response.json();

if (!/^3\.0\./.test(document.openapi ?? '')) {
  console.error(`Unexpected OpenAPI version: ${document.openapi ?? 'missing'}`);
  process.exit(1);
}

if (document['x-itunda-contract-source'] !== 'runtime-service-openapi') {
  console.error('Refusing to persist an OpenAPI document that was not generated by the verified Itunda runtime aggregator.');
  process.exit(1);
}

const pathCount = Object.keys(document.paths ?? {}).length;
if (pathCount === 0) {
  console.error('Refusing to persist an OpenAPI document with zero paths.');
  process.exit(1);
}

await mkdir('client', { recursive: true });
await writeFile('client/openapi.json', JSON.stringify(document, null, 2) + '\n');
console.log(`Wrote client/openapi.json with ${pathCount} verified paths from ${url}`);
